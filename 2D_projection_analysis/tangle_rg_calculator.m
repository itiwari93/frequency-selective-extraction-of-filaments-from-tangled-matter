%% TANGLE 2D COMPACTION ANALYSIS
%
% Calculates from source TIFF images:
%
%   1. Radius of gyration, Rg
%   2. PCA major-axis RMS spread
%   3. PCA minor-axis RMS spread
%   4. PCA aspect ratio / anisotropy
%   5. R50, R80, R90, R95
%   6. Projected foreground area
%
% Image segmentation uses a morphological-gradient mask followed by
% closing, hole filling, and foreground-intensity thresholding.
%
% Expected filenames:
%
%   0_1.tif
%   0_2.tif
%   0_3.tif
%
%   2_1.tif
%   2_2.tif
%   2_3.tif
%
%   10_1.tif
%   10_2.tif
%   10_3.tif
%
% Put this script in the same folder as the TIFF files.
%
% Output:
%   - one MATLAB table containing all individual measurements
%   - one table containing condition mean +/- SD
%   - diagnostic figures
%   - CSV files
%
% -------------------------------------------------------------

clear;
clc;
close all;


%% ============================================================
% SETTINGS
% ============================================================

% Image calibration in pixels per millimetre.
pixelsPerMillimetre = 118.54;

% Conditions to analyze.
conditions = [0, 2, 10];

% Three independent tangles per condition.
numberOfReplicates = 3;

% Foreground intensity threshold.
finalIntensityThreshold = 0.20;

% Morphological-gradient threshold.
gradientThreshold = 0.05;

% Whether to display one diagnostic figure per image.
showDiagnosticFigures = true;

% Whether to save diagnostic figures.
saveDiagnosticFigures = false;

diagnosticFolder = 'tangle_compaction_diagnostics';

if saveDiagnosticFigures && ~isfolder(diagnosticFolder)
    mkdir(diagnosticFolder);
end


%% ============================================================
% STORAGE
% ============================================================

Condition = [];
Replicate = [];

RadiusOfGyration_mm = [];

PCA_MajorRMS_mm = [];
PCA_MinorRMS_mm = [];
PCA_AspectRatio = [];

R50_mm = [];
R80_mm = [];
R90_mm = [];
R95_mm = [];

ProjectedPixelArea_px2 = [];
ProjectedArea_mm2 = [];

CentroidX_px = [];
CentroidY_px = [];


%% ============================================================
% LOOP THROUGH ALL IMAGES
% ============================================================

resultIndex = 0;

for conditionIndex = 1:numel(conditions)

    currentCondition = conditions(conditionIndex);

    for replicateIndex = 1:numberOfReplicates

        resultIndex = resultIndex + 1;


        %% ----------------------------------------------------
        % LOAD IMAGE
        % -----------------------------------------------------

        fileName = sprintf(...
            '%d_%d.tif', ...
            currentCondition, ...
            replicateIndex);


        if ~isfile(fileName)

            error(...
                'Could not find file: %s', ...
                fileName);

        end


        fprintf(...
            'Analyzing %s\n', ...
            fileName);


        frameOriginal = imread(fileName);


        % Convert to grayscale double image in range [0,1].
        frame = im2double(...
            im2gray(frameOriginal));


        %% ====================================================
        % SEGMENT TANGLE
        %
        % Identify the tangle region before applying the intensity threshold.
        % =====================================================

        SE = strel(...
            'Disk', ...
            1, ...
            4);


        % Morphological gradient.
        morphologicalGradient = ...
            imsubtract(...
            imdilate(frame, SE), ...
            imerode(frame, SE));


        % Binary threshold applied to the morphological gradient:
        %
        %     im2bw(morphologicalGradient,0.05)
        %
        mask = ...
            morphologicalGradient > gradientThreshold;


        % Close small gaps.
        mask = ...
            imclose(mask, SE);


        % Fill enclosed regions.
        mask = ...
            imfill(mask, 'holes');


        % Keep largest connected object.
        mask = ...
            bwareafilt(mask, 1);


        % Include background components smaller than 5000 pixels.
        notMask = ...
            ~mask;


        mask = ...
            mask | ...
            bwpropfilt(...
            notMask, ...
            'Area', ...
            [-Inf, 5000 - eps(5000)]);


        %% ----------------------------------------------------
        % APPLY MASK TO ORIGINAL IMAGE
        % -----------------------------------------------------

        segmentedFrame = ...
            frame .* mask;


        % Foreground intensity threshold.
        filamentMask = ...
            segmentedFrame > finalIntensityThreshold;


        %% ----------------------------------------------------
        % GET FOREGROUND PIXEL COORDINATES
        % -----------------------------------------------------

        [row, column] = ...
            find(filamentMask);


        if numel(row) < 10

            error(...
                ['Segmentation failed or returned too few ', ...
                 'pixels for %s.'], ...
                fileName);

        end


        %% ====================================================
        % CENTROID
        % =====================================================

        centroidX = ...
            mean(column);


        centroidY = ...
            mean(row);


        xCentered_px = ...
            column - centroidX;


        yCentered_px = ...
            row - centroidY;


        %% ====================================================
        % RADIAL DISTANCES
        % =====================================================

        radialDistance_px = ...
            sqrt(...
            xCentered_px.^2 ...
            + yCentered_px.^2);


        radialDistance_mm = ...
            radialDistance_px ...
            / pixelsPerMillimetre;


        %% ====================================================
        % RADIUS OF GYRATION
        %
        % Rg^2 = mean(r^2)
        % =====================================================

        currentRg_mm = ...
            sqrt(...
            mean(radialDistance_mm.^2));


        %% ====================================================
        % PCA
        %
        % Build covariance matrix of foreground pixel positions.
        %
        % Eigenvectors:
        %     principal directions
        %
        % Eigenvalues:
        %     variance along each principal direction
        % =====================================================

        XY = [...
            xCentered_px, ...
            yCentered_px];


        covarianceMatrix_px2 = ...
            cov(XY, 1);


        [eigenvectors, eigenvalueMatrix] = ...
            eig(covarianceMatrix_px2);


        eigenvalues_px2 = ...
            diag(eigenvalueMatrix);


        % Sort from largest to smallest.
        [eigenvalues_px2, sortIndex] = ...
            sort(...
            eigenvalues_px2, ...
            'descend');


        eigenvectors = ...
            eigenvectors(:, sortIndex);


        lambdaMajor_px2 = ...
            eigenvalues_px2(1);


        lambdaMinor_px2 = ...
            eigenvalues_px2(2);


        %% ----------------------------------------------------
        % RMS SPREAD ALONG PRINCIPAL AXES
        % -----------------------------------------------------

        sigmaMajor_mm = ...
            sqrt(lambdaMajor_px2) ...
            / pixelsPerMillimetre;


        sigmaMinor_mm = ...
            sqrt(lambdaMinor_px2) ...
            / pixelsPerMillimetre;


        %% ----------------------------------------------------
        % PCA ASPECT RATIO
        %
        % = 1 means isotropic/circular in projection.
        % > 1 means elongated.
        % -----------------------------------------------------

        aspectRatio = ...
            sqrt(...
            lambdaMajor_px2 ...
            / lambdaMinor_px2);


        %% ====================================================
        % RADIAL PERCENTILES
        % =====================================================

        percentileRadii_mm = ...
            prctile(...
            radialDistance_mm, ...
            [50, 80, 90, 95]);


        currentR50_mm = ...
            percentileRadii_mm(1);


        currentR80_mm = ...
            percentileRadii_mm(2);


        currentR90_mm = ...
            percentileRadii_mm(3);


        currentR95_mm = ...
            percentileRadii_mm(4);


        %% ====================================================
        % PROJECTED AREA
        % =====================================================

        currentPixelArea = ...
            nnz(filamentMask);


        currentProjectedArea_mm2 = ...
            currentPixelArea ...
            / pixelsPerMillimetre^2;


        %% ====================================================
        % STORE RESULTS
        % =====================================================

        Condition(resultIndex, 1) = ...
            currentCondition;


        Replicate(resultIndex, 1) = ...
            replicateIndex;


        RadiusOfGyration_mm(resultIndex, 1) = ...
            currentRg_mm;


        PCA_MajorRMS_mm(resultIndex, 1) = ...
            sigmaMajor_mm;


        PCA_MinorRMS_mm(resultIndex, 1) = ...
            sigmaMinor_mm;


        PCA_AspectRatio(resultIndex, 1) = ...
            aspectRatio;


        R50_mm(resultIndex, 1) = ...
            currentR50_mm;


        R80_mm(resultIndex, 1) = ...
            currentR80_mm;


        R90_mm(resultIndex, 1) = ...
            currentR90_mm;


        R95_mm(resultIndex, 1) = ...
            currentR95_mm;


        ProjectedPixelArea_px2(resultIndex, 1) = ...
            currentPixelArea;


        ProjectedArea_mm2(resultIndex, 1) = ...
            currentProjectedArea_mm2;


        CentroidX_px(resultIndex, 1) = ...
            centroidX;


        CentroidY_px(resultIndex, 1) = ...
            centroidY;


        %% ====================================================
        % PRINT CURRENT RESULT
        % =====================================================

        fprintf(...
            ['  Rg = %.3f mm | ', ...
             'major = %.3f mm | ', ...
             'minor = %.3f mm | ', ...
             'aspect = %.3f | ', ...
             'R80 = %.3f mm\n'], ...
            currentRg_mm, ...
            sigmaMajor_mm, ...
            sigmaMinor_mm, ...
            aspectRatio, ...
            currentR80_mm);


        %% ====================================================
        % DIAGNOSTIC FIGURE
        % =====================================================

        if showDiagnosticFigures || saveDiagnosticFigures


            diagnosticFigure = figure(...
                'Color', 'w', ...
                'Position', [100, 100, 900, 750], ...
                'Visible', 'on');


            imshow(frameOriginal);

            hold on;


            %% ------------------------------------------------
            % CENTROID
            % -------------------------------------------------

            plot(...
                centroidX, ...
                centroidY, ...
                'r+', ...
                'MarkerSize', 14, ...
                'LineWidth', 2);


            %% ------------------------------------------------
            % PRINCIPAL AXES
            %
            % Draw +/- 2 sigma for visualization.
            % -------------------------------------------------

            majorDirection = ...
                eigenvectors(:, 1);


            minorDirection = ...
                eigenvectors(:, 2);


            sigmaMajor_px = ...
                sqrt(lambdaMajor_px2);


            sigmaMinor_px = ...
                sqrt(lambdaMinor_px2);


            majorStart = ...
                [centroidX; centroidY] ...
                - 2 * sigmaMajor_px ...
                * majorDirection;


            majorEnd = ...
                [centroidX; centroidY] ...
                + 2 * sigmaMajor_px ...
                * majorDirection;


            minorStart = ...
                [centroidX; centroidY] ...
                - 2 * sigmaMinor_px ...
                * minorDirection;


            minorEnd = ...
                [centroidX; centroidY] ...
                + 2 * sigmaMinor_px ...
                * minorDirection;


            plot(...
                [majorStart(1), majorEnd(1)], ...
                [majorStart(2), majorEnd(2)], ...
                'y-', ...
                'LineWidth', 2);


            plot(...
                [minorStart(1), minorEnd(1)], ...
                [minorStart(2), minorEnd(2)], ...
                'c-', ...
                'LineWidth', 2);


            %% ------------------------------------------------
            % RADIUS-OF-GYRATION CIRCLE
            % -------------------------------------------------

            theta = ...
                linspace(0, 2*pi, 400);


            Rg_px = ...
                currentRg_mm ...
                * pixelsPerMillimetre;


            plot(...
                centroidX ...
                + Rg_px*cos(theta), ...
                centroidY ...
                + Rg_px*sin(theta), ...
                'w--', ...
                'LineWidth', 1.5);


            %% ------------------------------------------------
            % R80 CIRCLE
            % -------------------------------------------------

            R80_px = ...
                currentR80_mm ...
                * pixelsPerMillimetre;


            plot(...
                centroidX ...
                + R80_px*cos(theta), ...
                centroidY ...
                + R80_px*sin(theta), ...
                'g--', ...
                'LineWidth', 1.5);


            title(sprintf(...
                ['%d TW, replicate %d\n', ...
                 'R_g = %.2f mm, ', ...
                 'R_{80} = %.2f mm, ', ...
                 'aspect = %.2f'], ...
                currentCondition, ...
                replicateIndex, ...
                currentRg_mm, ...
                currentR80_mm, ...
                aspectRatio));


            legend(...
                {'Centroid', ...
                 'PCA major axis', ...
                 'PCA minor axis', ...
                 'R_g', ...
                 'R_{80}'}, ...
                'Location', 'bestoutside');


            if saveDiagnosticFigures

                exportgraphics(...
                    diagnosticFigure, ...
                    fullfile(...
                    diagnosticFolder, ...
                    sprintf(...
                    '%dTW_R%d_compaction_diagnostic.png', ...
                    currentCondition, ...
                    replicateIndex)), ...
                    'Resolution', 200);

            end

        end

    end
end


